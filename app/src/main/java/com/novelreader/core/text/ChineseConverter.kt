    /** 把「单字符 → 单字符」的对照转成 Char 映射；非单字符项（若有）直接跳过，不影响其余 */
    private fun toCharMap(swap: Boolean): Map<Char, Char> =
        PAIRS.mapNotNull { (s, t) ->
            val from = if (swap) t else s
            val to = if (swap) s else t
            val fc = from.singleOrNull()
            val tc = to.singleOrNull()
            if (fc != null && tc != null) fc to tc else null
        }.toMap()

    /** 简 → 繁 */
    private val S2T: Map<Char, Char> by lazy { toCharMap(swap = false) }

    /** 繁 → 简 */
    private val T2S: Map<Char, Char> by lazy { toCharMap(swap = true) }

    /**
     * 按模式转换文本。
     *
     * @param text 原文
     * @param mode 0=不转换 1=简转繁 2=繁转简
     * @return 转换后的文本；模式为 0 或原文为空时原样返回
     */
    fun convert(text: String, mode: Int): String {
        if (text.isEmpty() || mode == 0) return text
        val map = if (mode == 2) T2S else S2T
        val sb = StringBuilder(text.length)
        for (c in text) {
            sb.append(map[c] ?: c)
        }
        return sb.toString()
    }

    /** 简转繁 */
    fun toTraditional(text: String): String = convert(text, 1)

    /** 繁转简 */
    fun toSimplified(text: String): String = convert(text, 2)
